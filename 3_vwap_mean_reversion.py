import numpy as np
import pandas as pd
import pandas_ta as ta

def calculate_vwap(df: pd.DataFrame, window: int | None = None) -> pd.Series:
    """Session VWAP (window=None) or rolling VWAP"""
    tp = (df["high"] + df["low"] + df["close"]) / 3.0
    if window is None:
        # Session VWAP – resets every day
        dates = df.index.date
        cum_vol = df["volume"].groupby(dates).cumsum()
        cum_tp_vol = (tp * df["volume"]).groupby(dates).cumsum()
        return cum_tp_vol / cum_vol
    else:
        return (tp * df["volume"]).rolling(window, min_periods=1).sum() / \
               df["volume"].rolling(window, min_periods=1).sum()

def make_extreme_3vwap_signal(
    df: pd.DataFrame,
    # --- Best parameters found ---
    band: float = 0.00616,          # ~0.616%
    adx_th: float = 20.93,          # ADX must be BELOW this (ranging)
    vol_mult: float = 1.90,         # Volume > 1.90 × MA20
    sl_pct: float = 0.00377,        # 1:1
    tp_pct: float = 0.00377,
    bias: str = "short_only",       # "both" | "long_only" | "short_only"
    use_rejection: bool = False,
) -> pd.Series:
    """
    Returns signal Series:
        1  = Long
       -1  = Short
        0  = Flat
    """
    required = ["open", "high", "low", "close", "volume"]
    if not all(c in df.columns for c in required):
        raise ValueError(f"DataFrame must contain: {required}")

    df = df.copy()

    # ========== 3 VWAPs ==========
    df["vwap_sess"] = calculate_vwap(df, None)       # Session
    df["vwap_12"]   = calculate_vwap(df, 12)         # ~1 hour
    df["vwap_78"]   = calculate_vwap(df, 78)         # ~6.5 hours

    # ========== ADX ==========
    adx_df = ta.adx(df["high"], df["low"], df["close"], length=14)
    df["adx"] = adx_df["ADX_14"]

    # ========== Volume ==========
    df["vol_ma20"] = df["volume"].rolling(20).mean()
    df["vol_ma10"] = df["volume"].rolling(10).mean()

    # ========== Clean ==========
    df = df.dropna()

    close = df["close"]
    high  = df["high"]
    low   = df["low"]
    vol   = df["volume"]
    adx   = df["adx"]
    open_ = df["open"]

    v1 = df["vwap_sess"]
    v2 = df["vwap_12"]
    v3 = df["vwap_78"]

    # ========== Core Conditions ==========
    long_cond = (
        (close < v1 * (1 - band)) &
        (close < v2 * (1 - band)) &
        (close < v3 * (1 - band)) &
        (adx < adx_th) &
        (vol > df["vol_ma20"] * vol_mult) &
        (vol > df["vol_ma10"] * 1.1)
    )

    short_cond = (
        (close > v1 * (1 + band)) &
        (close > v2 * (1 + band)) &
        (close > v3 * (1 + band)) &
        (adx < adx_th) &
        (vol > df["vol_ma20"] * vol_mult) &
        (vol > df["vol_ma10"] * 1.1)
    )

    # Optional rejection candle
    if use_rejection:
        long_cond  = long_cond  & (close > open_)
        short_cond = short_cond & (close < open_)

    # ========== Build Signal ==========
    signal = pd.Series(0, index=df.index, dtype=int)
    signal[long_cond]  = 1
    signal[short_cond] = -1

    if bias == "long_only":
        signal = signal.where(signal == 1, 0)
    elif bias == "short_only":
        signal = signal.where(signal == -1, 0)

    return signal

