def backtest_with_trades(df, signal, sl_pct=0.00377, tp_pct=0.00377, cost=0.00012):
    signal = signal.reindex(df.index).fillna(0).astype(int)

    close = df["close"].values
    high  = df["high"].values
    low   = df["low"].values
    times = df.index.to_numpy()
    sig   = signal.values

    position = 0
    entry_price = 0.0
    entry_time = None
    entry_idx = 0
    trades = []

    for i in range(1, len(close)):
        if position == 0:
            if sig[i] == 1 and sig[i-1] != 1:
                position = 1
                entry_price = close[i]
                entry_time = times[i]
                entry_idx = i
            elif sig[i] == -1 and sig[i-1] != -1:
                position = -1
                entry_price = close[i]
                entry_time = times[i]
                entry_idx = i

        elif position == 1:
            hit_sl = low[i] <= entry_price * (1 - sl_pct)
            hit_tp = high[i] >= entry_price * (1 + tp_pct)
            if hit_sl or hit_tp or sig[i] != 1:
                if hit_sl:
                    exit_p = entry_price * (1 - sl_pct)
                    reason = "SL"
                elif hit_tp:
                    exit_p = entry_price * (1 + tp_pct)
                    reason = "TP"
                else:
                    exit_p = close[i]
                    reason = "Signal"
                ret = (exit_p / entry_price - 1) - 2 * cost
                trades.append({
                    "entry_time": entry_time,
                    "exit_time": times[i],
                    "direction": "LONG",
                    "entry_price": round(entry_price, 2),
                    "exit_price": round(exit_p, 2),
                    "return_%": round(ret * 100, 3),
                    "result": "WIN" if ret > 0 else "LOSS",
                    "reason": reason,
                    "bars_held": i - entry_idx
                })
                position = 0

        elif position == -1:
            hit_sl = high[i] >= entry_price * (1 + sl_pct)
            hit_tp = low[i] <= entry_price * (1 - tp_pct)
            if hit_sl or hit_tp or sig[i] != -1:
                if hit_sl:
                    exit_p = entry_price * (1 + sl_pct)
                    reason = "SL"
                elif hit_tp:
                    exit_p = entry_price * (1 - tp_pct)
                    reason = "TP"
                else:
                    exit_p = close[i]
                    reason = "Signal"
                ret = (entry_price / exit_p - 1) - 2 * cost
                trades.append({
                    "entry_time": entry_time,
                    "exit_time": times[i],
                    "direction": "SHORT",
                    "entry_price": round(entry_price, 2),
                    "exit_price": round(exit_p, 2),
                    "return_%": round(ret * 100, 3),
                    "result": "WIN" if ret > 0 else "LOSS",
                    "reason": reason,
                    "bars_held": i - entry_idx
                })
                position = 0

    trades_df = pd.DataFrame(trades)

    if len(trades_df) == 0:
        print("Δεν βρέθηκαν συναλλαγές!")
        return None, trades_df

    total_trades = len(trades_df)
    wins = (trades_df["result"] == "WIN").sum()
    losses = total_trades - wins
    winrate = wins / total_trades * 100
    total_return = trades_df["return_%"].sum()
    avg_return = trades_df["return_%"].mean()
    pos_sum = trades_df.loc[trades_df["return_%"] > 0, "return_%"].sum()
    neg_sum = abs(trades_df.loc[trades_df["return_%"] < 0, "return_%"].sum())
    profit_factor = pos_sum / neg_sum if neg_sum > 0 else np.inf

    print("\n" + "="*70)
    print("ΣΥΝΟΨΗ ΣΥΝΑΛΛΑΓΩΝ")
    print("="*70)
    print(f"Συνολικές συναλλαγές : {total_trades}")
    print(f"Κερδισμένες (WIN)     : {wins}")
    print(f"Χαμένες (LOSS)        : {losses}")
    print(f"Win Rate              : {winrate:.1f}%")
    print(f"Συνολικό αποτέλεσμα   : {total_return:+.2f}%")
    print(f"Μέσο αποτέλεσμα/trade : {avg_return:+.3f}%")
    print(f"Profit Factor         : {profit_factor:.2f}")
    print("="*70)

    return {"total_trades": total_trades, "winrate": winrate, "total_return_%": total_return}, trades_df

